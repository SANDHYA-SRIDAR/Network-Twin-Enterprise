"""Export the Pydantic source of truth to JSON Schema and frontend types.

Run from backend: python export_contract.py [--check]
"""
import json
from pathlib import Path
import sys

from app.models.network import NetworkDefinition


def ts_type(schema):
    if "const" in schema:
        return json.dumps(schema["const"])
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(v) for v in schema["anyOf"])
    kind = schema.get("type")
    if kind == "object":
        if "properties" not in schema:
            extra = schema.get("additionalProperties", {})
            return f"Record<string, {ts_type(extra) if isinstance(extra, dict) else 'unknown'}>"
        required = schema.get("required", [])
        fields = [f"  {json.dumps(k)}{'' if k in required else '?'}: {ts_type(v)};" for k, v in schema["properties"].items()]
        return "{\n" + "\n".join(fields) + "\n}"
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def outputs():
    root = Path(__file__).resolve().parent.parent
    schema = NetworkDefinition.model_json_schema()
    types = "// Generated by backend/export_contract.py. Edit the Pydantic models, then regenerate.\n/* eslint-disable prettier/prettier -- generated contract; verify with export_contract.py --check */\n"
    for name, definition in {**schema.get("$defs", {}), "NetworkDefinition": schema}.items():
        types += f"export type {name} = {ts_type(definition)};\n\n"
    return {
        root / "docs/network-definition.schema.json": json.dumps(schema, indent=2) + "\n",
        root / "src/lib/network-contract.ts": types,
    }


if __name__ == "__main__":
    for path, content in outputs().items():
        if "--check" in sys.argv:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Canonical schema export is stale: {path.name}")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
